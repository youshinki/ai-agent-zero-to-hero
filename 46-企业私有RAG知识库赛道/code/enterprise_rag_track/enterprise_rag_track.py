# 四、私有 RAG 演示（轻量实现）
# ======================================================================

class MiniRAG:
    def __init__(self):
        self.docs: List[Dict] = []
    
    def add(self, source: str, content: str):
        self.docs.append({"source": source, "content": content})
    
    @staticmethod
    def _score(q: str, c: str) -> float:
        qs = set(q.replace(" ", ""))
        cs = set(c.replace(" ", ""))
        if not qs:
            return 0.0
        return len(qs & cs) / len(qs)
    
    def search(self, query: str, top_k: int = 2) -> List[Dict]:
        scored = [{"source": d["source"], "content": d["content"],
                   "score": round(self._score(query, d["content"]), 3)}
                  for d in self.docs]
        scored.sort(key=lambda x: x["score"], reverse=True)
        return scored[:top_k]
    
    def answer(self, query: str) -> str:
        hits = self.search(query)
        if not hits or hits[0]["score"] < 0.2:
            return "知识库中暂无相关信息，建议补充资料。"
        top = hits[0]
        return (f"根据《{top['source']}》回答：\n{top['content']}\n\n"
                f"（来源：{top['source']}，相关度 {top['score']}）")


