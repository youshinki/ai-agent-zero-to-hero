# ======================================================================
# 生成全部文档
# ======================================================================

def generate_all(project_name="企业私有智能问答知识库系统", client="客户名称"):
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    docs = {
        "01_交付清单.md": DeliveryChecklist.generate(project_name, client),
        "02_使用手册.md": UserManual.generate(project_name),
        "03_售后维护方案.md": AfterSalePolicy.generate(),
        "04_需求确认书.md": RequirementForm.generate(),
    }
    paths = []
    for name, content in docs.items():
        path = os.path.join(OUTPUT_DIR, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        paths.append(path)
    return paths


if __name__ == "__main__":
    print("=" * 60)
    print("📦 生成标准化交付文档")
    print("=" * 60)
    paths = generate_all()
    for p in paths:
        size = os.path.getsize(p)
        print(f"   ✅ {p}（{size}字节）")
    print("\n交付文档已生成，可直接发给客户。")
