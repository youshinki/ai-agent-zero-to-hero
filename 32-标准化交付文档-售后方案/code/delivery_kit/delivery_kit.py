# ======================================================================
# 三、售后边界方案
# ======================================================================

class AfterSalePolicy:
    FREE_ITEMS = [
        "系统部署调试、运行故障排查",
        "基础使用教学、操作答疑",
        "交付后 7 天内非人为 BUG 免费修复",
        "单次项目资料一次性完整入库调试",
    ]
    
    PAID_ITEMS = [
        "后期频繁新增、大批量替换企业资料（按需收费）",
        "新增额外功能、定制化开发需求",
        "界面改版、系统重构、多端适配",
        "超出资质的模型接入、第三方系统对接",
        "7 天后的故障修复与长期运维（可签维护合同）",
    ]
    
    SLA = {
        "P0 系统崩溃": "30 分钟响应，2 小时修复",
        "P1 功能异常": "2 小时响应，8 小时修复",
        "P2 体验优化": "24 小时响应，下个版本处理",
    }
    
    @classmethod
    def generate(cls) -> str:
        free = "\n".join(f"- {x}" for x in cls.FREE_ITEMS)
        paid = "\n".join(f"- {x}" for x in cls.PAID_ITEMS)
        sla = "\n".join(f"| {k} | {v} |" for k, v in cls.SLA.items())
        return f"""# 售后维护服务说明（免费 / 有偿边界）

## 一、免费售后范围（交付必含）

{free}

## 二、有偿服务范围（杜绝白嫖）

{paid}

## 三、服务等级（SLA）

| 故障等级 | 响应与修复 |
|----------|------------|
{sla}

## 四、免责说明

1. 因第三方 API 变更导致的问题不属乙方责任
2. 甲方自行修改代码/配置导致的问题不在维护范围内
3. 不可抗力因素导致的服务中断不属违约

## 五、维护合同（可选）

- 基础托管：1000-2000 元/月
- 标准托管：3000-5000 元/月
- 高级托管：8000-15000 元/月
"""


