def generate_manual() -> str:
    out = ["# AI接单成交话术手册\n"]
    out.append("> 沟通固定顺序：展示案例 → 调研需求 → 评估项目 → 给出报价 → 确认清单\n")
    
    out.append("\n## 一、六阶段标准话术\n")
    for stage, info in SCRIPTS.items():
        out.append(f"### {stage}\n")
        out.append(f"**客户**：{info['customer']}\n")
        out.append(f"**回复**：{info['reply']}\n")
        out.append(f"**要点**：{' / '.join(info['points'])}\n")
    
    out.append("\n## 二、高频异议应对\n")
    for name, info in OBJECTIONS.items():
        out.append(f"### {name}\n**客户**：{info['customer']}\n\n**回复**：{info['reply']}\n")
    
    out.append("\n## 三、沟通红线\n")
    for i, line in enumerate(RED_LINES, 1):
        out.append(f"{i}. {line}\n")
    
    return "\n".join(out)


