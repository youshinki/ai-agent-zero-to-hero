class SalesSimulator:
    """话术陪练：根据客户输入匹配最佳应对"""
    
    def match(self, customer_input: str) -> dict:
        text = customer_input
        rules = [
            (["便宜", "贵", "300", "价格高", "别家"], OBJECTIONS["比价"]),
            (["试用", "先试", "满意再付", "免费做"], OBJECTIONS["免费试用"]),
            (["泄露", "安全", "隐私", "上传"], OBJECTIONS["资料泄露"]),
            (["再加", "增加功能", "改需求", "顺便"], OBJECTIONS["无限加需求"]),
            (["多少钱", "报价", "价格"], SCRIPTS["阶段4 报价谈判"]),
            (["怎么做", "你好", "在吗"], SCRIPTS["阶段1 初次接待"]),
        ]
        for keywords, script in rules:
            if any(k in text for k in keywords):
                return script
        return {"customer": text,
                "reply": "感谢咨询！方便说下您的具体场景和需求吗？我免费出方案和报价。",
                "points": ["先问需求", "再出方案", "最后报价"]}


