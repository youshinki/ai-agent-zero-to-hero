# ======================================================================
# 五、纠纷处理流程
# ======================================================================

DISPUTE_FLOW = [
    ("核对依据", "调取双方确认的需求清单与协议原文，核对争议点是否在约定交付范围内"),
    ("分类处理", "属于BUG → 免费修复；属于新增需求 → 单独报价，双方确认后开发"),
    ("书面留痕", "所有沟通通过文字进行，截图保存聊天记录与确认信息"),
    ("冷静沟通", "不与客户争辩技术优劣，用演示与文档说话"),
    ("终止机制", "无法协商时，按已完成工作量结算，签署终止协议，交付已完成部分"),
]


# ======================================================================
# 生成
# ======================================================================

def build_all(party_a="XX科技有限公司", party_b="开发者", tier="L2 商用标准版",
              total_price=1200, workdays=3):
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    files = {
        "01_服务协议.md": build_agreement(party_a, party_b, tier, total_price,
                                          workdays=workdays),
        "02_需求变更确认单.md": build_change_form(),
    }
    risk_text = "# 项目风险清单与应对\n\n"
    for name, info in RISKS.items():
        risk_text += f"## {name}（{info['severity']}）\n"
        risk_text += f"- 成因：{info['cause']}\n- 应对：{info['mitigation']}\n\n"
    risk_text += "\n# 纠纷处理流程\n\n"
    for i, (title, detail) in enumerate(DISPUTE_FLOW, 1):
        risk_text += f"{i}. **{title}**：{detail}\n"
    files["03_风险清单与纠纷流程.md"] = risk_text
    
    paths = []
    for name, content in files.items():
        path = os.path.join(OUTPUT_DIR, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        paths.append(path)
    return paths


if __name__ == "__main__":
    print("=" * 60)
    print("⚖️ 生成协议与风险清单")
    print("=" * 60)
    paths = build_all()
    for p in paths:
        print(f"   ✅ {p}（{os.path.getsize(p)}字节）")
