# ======================================================================
# 生成完整发布包
# ======================================================================

def build_listing_package(tier: str = "标准版") -> list:
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    files = {}
    
    # 1. 账号配置
    files["01_账号配置.md"] = AccountSetup.generate()
    
    # 2. 标题（3套）
    titles = "# 高曝光标题模板\n\n"
    for i, (scene, title) in enumerate(TITLE_TEMPLATES.items(), 1):
        titles += f"## 模板{i}｜{scene}\n{title}\n\n"
    files["02_标题模板.md"] = titles
    
    # 3. 详情页
    files["03_详情页.md"] = DetailPage.generate()
    
    # 4. 定价
    price_text = "# 定价区间策略\n\n"
    for name, info in PRICING.items():
        price = f"{info['price']}元" if isinstance(info["price"], int) else f"{info['price']}元"
        price_text += f"## {name}：{price}\n"
        for item in info["includes"]:
            price_text += f"- {item}\n"
        price_text += f"- 适合：{info['suitable']}\n\n"
    files["04_定价策略.md"] = price_text
    
    # 5. 咨询规则与运营计划
    rules = "# 咨询回复规则\n\n" + "\n".join(f"{i}. {r}" for i, r in enumerate(REPLY_RULES, 1))
    rules += "\n\n# 7天运营计划\n\n"
    for period, items in OPERATION_PLAN.items():
        rules += f"## {period}\n"
        for item in items:
            rules += f"- {item}\n"
        rules += "\n"
    files["05_运营计划.md"] = rules
    
    # 6. 发布文案（用于复制粘贴）
    listing = f"""# 闲鱼商品发布文案（{tier}）

## 标题
{TITLE_TEMPLATES['企业私有知识库（高客单主赛道）']}

## 详情
{DetailPage.generate()}

## 价格
{PRICING[tier]['price']}元（{tier}）

## 交付
{('、'.join(PRICING[tier]['includes']))}
"""
    files["06_发布文案.md"] = listing
    
    paths = []
    for name, content in files.items():
        path = os.path.join(OUTPUT_DIR, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        paths.append(path)
    return paths


if __name__ == "__main__":
    print("=" * 60)
    print("🐟 生成闲鱼完整发布包")
    print("=" * 60)
    paths = build_listing_package()
    for p in paths:
        print(f"   ✅ {p}（{os.path.getsize(p)}字节）")
    print("\n发布包已生成，可直接复制到闲鱼。")
